#!/usr/bin/env node

/**
 * Generates a list of image URLs to precache based on menu.json.
 * Extracts all image URLs from the base `image` field and any srcset variants
 * in the `imageSet` field. Also reads manifest.json files from public/images/
 * to include all generated responsive image variants.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MENU_DATA_PATH = path.join(ROOT, 'data', 'menu.json');
const PUBLIC_IMAGES_DIR = path.join(ROOT, 'public', 'images');
// Output to scripts/precache-images.js for debugging and testing purposes
const OUTPUT_PATH = path.join(ROOT, 'scripts', 'precache-images.js');
// Also inject directly into service-worker.js for runtime use
const SERVICE_WORKER_PATH = path.join(ROOT, 'service-worker.js');
const MENU_IMAGES_START_MARKER = '// MENU_IMAGES_START - Auto-generated by tools/generate-precache-urls.js';
const MENU_IMAGES_END_MARKER = '// MENU_IMAGES_END';

/**
 * Extract all image URLs from a menu item's imageSet
 * @param {Object} item - Menu item with optional imageSet array
 * @returns {string[]} Array of image URLs
 */
function extractImageUrls(item) {
  if (!item || typeof item !== 'object') {
    return [];
  }

  const urls = [];

  // Add base image if present
  if (typeof item.image === 'string' && item.image.trim()) {
    urls.push(item.image.trim());
  }

  // Add all srcset variants
  const imageSet = Array.isArray(item.imageSet) ? item.imageSet : [];
  for (const entry of imageSet) {
    let src = '';

    if (typeof entry === 'string') {
      src = entry.trim();
    } else if (entry && typeof entry === 'object' && typeof entry.src === 'string') {
      src = entry.src.trim();
    }

    if (src && !urls.includes(src)) {
      urls.push(src);
    }
  }

  return urls;
}

/**
 * Extract all image URLs from menu data
 * @param {Object} data - Menu data object
 * @returns {string[]} Array of unique image URLs
 */
function extractAllImageUrls(data) {
  if (!data || typeof data !== 'object') {
    return [];
  }

  const allUrls = new Set();
  const sections = Array.isArray(data.sections) ? data.sections : [];

  for (const section of sections) {
    if (!section || !Array.isArray(section.items)) {
      continue;
    }

    for (const item of section.items) {
      const urls = extractImageUrls(item);
      urls.forEach(url => allUrls.add(url));
    }
  }

  return Array.from(allUrls).sort();
}

/**
 * Extract the slug from an image path
 * @param {string} imagePath - Path to the image (e.g., "assets/photos/Fajitas-Mixtas.png")
 * @returns {string|null} - The slug or null if not extractable
 */
function extractSlugFromPath(imagePath) {
  if (typeof imagePath !== 'string') {
    return null;
  }
  
  const basename = path.basename(imagePath);
  const nameWithoutExt = basename.replace(/\.[^.]+$/, '');
  return nameWithoutExt;
}

/**
 * Read all generated image variants from public/images/ manifests
 * @param {string[]} baseImageUrls - Array of base image URLs from menu.json
 * @param {boolean} onlyHighest - If true, only include the highest resolution variant per format
 * @returns {string[]} Array of all variant URLs
 */
function extractGeneratedVariants(baseImageUrls, onlyHighest = false) {
  if (!fs.existsSync(PUBLIC_IMAGES_DIR)) {
    console.warn(`Public images directory not found: ${PUBLIC_IMAGES_DIR}`);
    return [];
  }

  const variantUrls = new Set();

  for (const imageUrl of baseImageUrls) {
    const slug = extractSlugFromPath(imageUrl);
    if (!slug) {
      continue;
    }

    const manifestPath = path.join(PUBLIC_IMAGES_DIR, slug, 'manifest.json');
    if (!fs.existsSync(manifestPath)) {
      continue;
    }

    try {
      const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
      const variants = Array.isArray(manifest.variants) ? manifest.variants : [];

      if (onlyHighest) {
        // Group variants by format and find the highest width for each
        const highestByFormat = {};
        
        for (const variant of variants) {
          if (!variant.files || typeof variant.files !== 'object') {
            continue;
          }

          for (const [format, formatInfo] of Object.entries(variant.files)) {
            if (!formatInfo || typeof formatInfo.path !== 'string') {
              continue;
            }
            
            const currentWidth = variant.width || 0;
            const existingWidth = highestByFormat[format]?.width || 0;
            
            if (currentWidth > existingWidth) {
              highestByFormat[format] = {
                path: formatInfo.path,
                width: currentWidth
              };
            }
          }
        }
        
        // Add only the highest resolution for each format
        for (const info of Object.values(highestByFormat)) {
          variantUrls.add(info.path);
        }
      } else {
        // Add all format variants (avif, webp, jpg)
        for (const variant of variants) {
          if (!variant.files || typeof variant.files !== 'object') {
            continue;
          }

          for (const formatInfo of Object.values(variant.files)) {
            if (formatInfo && typeof formatInfo.path === 'string') {
              variantUrls.add(formatInfo.path);
            }
          }
        }
      }
    } catch (error) {
      console.warn(`Error reading manifest for ${slug}:`, error.message);
    }
  }

  return Array.from(variantUrls).sort();
}

/**
 * Update service-worker.js with the menu image URLs
 * @param {string[]} imageUrls - Array of image URLs to inject
 */
function updateServiceWorker(imageUrls) {
  if (!fs.existsSync(SERVICE_WORKER_PATH)) {
    console.warn(`Service worker not found at ${SERVICE_WORKER_PATH}`);
    return false;
  }

  try {
    let content = fs.readFileSync(SERVICE_WORKER_PATH, 'utf8');
    
    const startIndex = content.indexOf(MENU_IMAGES_START_MARKER);
    const endIndex = content.indexOf(MENU_IMAGES_END_MARKER);
    
    if (startIndex === -1 || endIndex === -1) {
      console.warn('Menu images markers not found in service-worker.js');
      return false;
    }

    // Build the replacement content
    const imageArrayStr = JSON.stringify(imageUrls, null, 2);
    const replacement = [
      MENU_IMAGES_START_MARKER,
      `const MENU_IMAGE_URLS = ${imageArrayStr};`,
      MENU_IMAGES_END_MARKER
    ].join('\n');

    // Replace the section between markers
    const before = content.substring(0, startIndex);
    const after = content.substring(endIndex + MENU_IMAGES_END_MARKER.length);
    const updated = before + replacement + after;

    fs.writeFileSync(SERVICE_WORKER_PATH, updated, 'utf8');
    console.log(`Updated ${SERVICE_WORKER_PATH}`);
    return true;
  } catch (error) {
    console.error('Error updating service worker:', error.message);
    return false;
  }
}

function main() {
  if (!fs.existsSync(MENU_DATA_PATH)) {
    console.error(`Menu data not found at ${MENU_DATA_PATH}`);
    process.exitCode = 1;
    return;
  }

  try {
    // Check for --only-highest flag
    const onlyHighest = process.argv.includes('--only-highest');
    
    const menuData = JSON.parse(fs.readFileSync(MENU_DATA_PATH, 'utf8'));
    const baseImageUrls = extractAllImageUrls(menuData);
    const generatedVariants = extractGeneratedVariants(baseImageUrls, onlyHighest);
    
    // Combine base images with all generated variants
    const allImageUrls = [...baseImageUrls, ...generatedVariants].sort();

    // Generate the output file as a JavaScript module
    const outputContent = [
      '// Auto-generated by tools/generate-precache-urls.js',
      '// Do not edit manually - this file is regenerated on each build',
      '',
      '// Image URLs extracted from menu.json and public/images/ manifests',
      onlyHighest 
        ? '// Includes base images and highest resolution variant per format'
        : '// Includes base images and all responsive variants (640w, 1280w, 1920w, etc.)',
      'const MENU_IMAGE_URLS = ' + JSON.stringify(allImageUrls, null, 2) + ';',
      '',
      '// Export for use in service worker or other modules',
      'if (typeof module !== "undefined" && module.exports) {',
      '  module.exports = MENU_IMAGE_URLS;',
      '}',
      ''
    ].join('\n');

    fs.writeFileSync(OUTPUT_PATH, outputContent, 'utf8');
    
    // Update service worker with the image URLs
    // Note: We maintain both outputs because:
    // - OUTPUT_PATH is used by tests to verify extraction logic
    // - SERVICE_WORKER_PATH is used at runtime by the service worker
    updateServiceWorker(allImageUrls);
    
    console.log(`Generated precache URLs:`);
    console.log(`  - Base images: ${baseImageUrls.length}`);
    console.log(`  - Generated variants: ${generatedVariants.length}`);
    console.log(`  - Total: ${allImageUrls.length}`);
    if (onlyHighest) {
      console.log(`  - Mode: Highest resolution only (--only-highest)`);
    }
    console.log(`Output written to: ${OUTPUT_PATH}`);
  } catch (error) {
    console.error('Error generating precache URLs:', error.message);
    process.exitCode = 1;
  }
}

main();
